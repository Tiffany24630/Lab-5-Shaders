use crate::color::Color;
use crate::framebuffer::Framebuffer;

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct HudState<'a> {
    pub target: &'a str,
    pub time: f32,
    pub paused: bool,
    pub speed: f32,
}

const PANEL: Color = Color::new_const(0.012, 0.025, 0.070);
const TEXT: Color = Color::new_const(0.92, 0.96, 1.0);
const SECONDARY: Color = Color::new_const(0.35, 0.82, 0.92);
const RUNNING: Color = Color::new_const(0.35, 0.90, 0.68);
const PAUSED: Color = Color::new_const(1.0, 0.70, 0.32);

pub fn draw(framebuffer: &mut Framebuffer, state: HudState<'_>) {
    fill_rect(framebuffer, 16, 16, 234, 76, PANEL);
    fill_rect(framebuffer, 550, 16, 234, 90, PANEL);
    fill_rect(framebuffer, 16, 510, 400, 74, PANEL);

    draw_text(framebuffer, 28, 26, "AETHERIA", 2, TEXT);
    draw_text(framebuffer, 28, 48, "TARGET", 1, SECONDARY);
    draw_text(framebuffer, 92, 46, state.target, 2, TEXT);

    draw_text(framebuffer, 562, 26, "TIME", 1, SECONDARY);
    draw_text(framebuffer, 610, 24, &format_fixed(state.time, 2), 2, TEXT);
    draw_text(framebuffer, 562, 50, if state.paused { "PAUSED" } else { "RUNNING" }, 1,
        if state.paused { PAUSED } else { RUNNING });
    draw_text(framebuffer, 562, 74, "SPEED", 1, SECONDARY);
    draw_text(framebuffer, 624, 72, &format_speed(state.speed), 2, TEXT);

    draw_text(framebuffer, 28, 520, "DRAG: ROTATE", 1, TEXT);
    draw_text(framebuffer, 170, 520, "WHEEL: ZOOM", 1, TEXT);
    draw_text(framebuffer, 28, 538, "1-8: SELECT TARGET", 1, SECONDARY);
    draw_text(framebuffer, 28, 556, "SPACE: PAUSE   R: RESET", 1, SECONDARY);
}

pub fn measure_text(text: &str, scale: usize) -> usize {
    let scale = scale.max(1);
    text.chars().count().saturating_mul(6).saturating_mul(scale)
}

fn draw_text(framebuffer: &mut Framebuffer, x: usize, y: usize, text: &str, scale: usize, color: Color) {
    let scale = scale.max(1);
    let mut cursor = x;
    for character in text.chars() {
        let glyph = glyph(character.to_ascii_uppercase());
        for (row, bits) in glyph.iter().enumerate() {
            for column in 0..5 {
                if bits & (1 << (4 - column)) != 0 {
                    fill_rect(framebuffer, cursor + column * scale, y + row * scale, scale, scale, color);
                }
            }
        }
        cursor = cursor.saturating_add(6 * scale);
    }
}

fn fill_rect(framebuffer: &mut Framebuffer, x: usize, y: usize, width: usize, height: usize, color: Color) {
    let max_x = x.saturating_add(width).min(framebuffer.width());
    let max_y = y.saturating_add(height).min(framebuffer.height());
    for py in y.min(max_y)..max_y {
        for px in x.min(max_x)..max_x {
            framebuffer.set_color_pixel(px, py, color);
        }
    }
}

fn format_fixed(value: f32, decimals: usize) -> String {
    let value = if value.is_finite() { value.max(0.0) } else { 0.0 };
    format!("{value:.decimals$}")
}

fn format_speed(value: f32) -> String {
    let value = if value.is_finite() { value.clamp(0.25, 4.0) } else { 1.0 };
    format!("{value:.2}X")
}

